"""Stage 5: constrained clustering. Greedy union by descending edge score; a merge is refused if the component would
hold >1 dbpedia or >1 forbes record (fullcontact may hold several near-duplicate profiles). Rejected edges logged."""
import os, json, itertools, pandas as pd, numpy as np
W=os.path.dirname(os.path.abspath(__file__)); ROOT=os.path.dirname(W)
N=pd.read_csv(f"{W}/state/normalized.csv"); D=pd.read_csv(f"{W}/state/decisions.csv")
G=pd.read_csv(f"{W}/state/fc_groups.csv").set_index("record_id").group.to_dict()
src=dict(zip(N.record_id,N.source))
parent={r:r for r in N.record_id}; cnt={r:{"dbpedia":0,"forbes":0,"fullcontact":0} for r in N.record_id}
for r in N.record_id: cnt[r][src[r]]=1
def find(x):
    while parent[x]!=x: parent[x]=parent[parent[x]]; x=parent[x]
    return x
def union(a,b):
    ra,rb=find(a),find(b)
    if ra==rb: return True
    c={k:cnt[ra][k]+cnt[rb][k] for k in cnt[ra]}
    if c["dbpedia"]>1 or c["forbes"]>1: return False
    parent[rb]=ra; cnt[ra]=c; return True
# 1) exact-duplicate fullcontact rows
for rid,g in G.items():
    if rid!=g: union(g,rid)
# 2) accepted cross-source edges, strongest first (deterministic tie-break on ids)
E=D[D.accepted].sort_values(["score","id1","id2"],ascending=[False,True,True])
rej=[]
for r in E.itertuples():
    if not union(r.id1,r.id2): rej.append(dict(id1=r.id1,id2=r.id2,rule=r.rule,score=r.score,reason="would put 2 dbpedia or 2 forbes records in one cluster"))
pd.DataFrame(rej).to_csv(f"{W}/state/rejected_edges.csv",index=False)
N["root"]=N.record_id.map(find)
# cluster id = smallest-ranked member id by source priority forbes > dbpedia > fullcontact (stable, native)
pri={"forbes":0,"dbpedia":1,"fullcontact":2}
N["pri"]=N.source.map(pri)
cid=N.sort_values(["pri","record_id"]).groupby("root").record_id.first()
N["cluster_id"]=N.root.map(cid)
M=N[["record_id","source","cluster_id"]]
M.to_csv(f"{W}/state/membership.csv",index=False)
# correspondences: every cross-source pair inside a cluster, with best direct evidence score if any
sc={}
for r in D[D.accepted].itertuples(): sc[(r.id1,r.id2)]=sc[(r.id2,r.id1)]=r.score
C=[]
for c,g in M.groupby("cluster_id"):
    for (a,sa),(b,sb) in itertools.combinations(zip(g.record_id,g.source),2):
        if sa!=sb:
            s=sc.get((a,b)); C.append(dict(id1=a,id2=b,score=round(min(1.0,s/30),4) if s else 0.5,direct=s is not None))
C=pd.DataFrame(C); C.to_csv(f"{W}/state/correspondences.csv",index=False)
# blocking export = union of blocking methods + the few transitive cluster pairs not generated by blocking (flagged)
B=pd.read_csv(f"{W}/state/candidates.csv"); bk=set(map(frozenset,zip(B.id1,B.id2)))
extra=[(a,b) for a,b in zip(C.id1,C.id2) if frozenset((a,b)) not in bk]
pd.DataFrame(extra,columns=["id1","id2"]).to_csv(f"{W}/state/closure_candidates.csv",index=False)
pd.concat([B[["id1","id2"]],pd.DataFrame(extra,columns=["id1","id2"])]).to_csv(f"{ROOT}/submission/blocking/candidates.csv",index=False)
sizes=M.groupby("cluster_id").size(); nsrc=M.groupby("cluster_id").source.nunique()
diag=dict(stage="clustering",records=len(M),clusters=int(sizes.size),singletons=int((sizes==1).sum()),
  size_dist={int(k):int(v) for k,v in sizes.value_counts().sort_index().items()},
  sources_per_cluster={int(k):int(v) for k,v in nsrc.value_counts().sort_index().items()},
  rejected_edges=len(rej),correspondences=len(C),direct=int(C.direct.sum()),transitive=int((~C.direct).sum()),closure_pairs_added_to_candidates=len(extra))
print(json.dumps(diag,indent=1)); json.dump(diag,open(f"{W}/state/cluster_diag.json","w"),indent=1)
